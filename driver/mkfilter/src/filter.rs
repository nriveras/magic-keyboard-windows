//! Filter role: lower filter on the keyboard collection (`HID\VID_05AC&PID_xxxx&MI_01&Col01`).
//!
//! It sits between kbdhid and the hidclass PDO, so every input report kbdhid reads passes through
//! our IRP_MJ_READ completion. Each report is decoded with the collection's preparsed data, run
//! through the mk-core engine and rebuilt in place with keyboard-page usages only. Virtual outputs
//! (media keys, shortcuts, sleep) go to the hub's VHF device.

use core::mem::{size_of, zeroed};
use core::ptr::{addr_of_mut, null_mut};

use mk_core::state::Notification;
use mk_core::{Config, Engine, Outputs, model};
use wdk::println;
use wdk_sys::{
    _HID_COLLECTION_INFORMATION, _HIDP_CAPS, _POOL_TYPE::NonPagedPoolNx,
    _WDF_EXECUTION_LEVEL::WdfExecutionLevelInheritFromParent,
    _WDF_IO_QUEUE_DISPATCH_TYPE::WdfIoQueueDispatchParallel, _WDF_MEMORY_DESCRIPTOR__bindgen_ty_1,
    _WDF_MEMORY_DESCRIPTOR__bindgen_ty_1__bindgen_ty_1,
    _WDF_MEMORY_DESCRIPTOR_TYPE::WdfMemoryDescriptorTypeBuffer,
    _WDF_REQUEST_SEND_OPTIONS_FLAGS::WDF_REQUEST_SEND_OPTION_TIMEOUT,
    _WDF_SYNCHRONIZATION_SCOPE::WdfSynchronizationScopeInheritFromParent,
    _WDF_TRI_STATE::WdfUseDefault, NTSTATUS, PHIDP_PREPARSED_DATA, PVOID,
    PWDF_REQUEST_COMPLETION_PARAMS, PWDFDEVICE_INIT, STATUS_NOT_SUPPORTED, STATUS_SUCCESS, ULONG,
    ULONG_PTR, WDF_IO_QUEUE_CONFIG, WDF_MEMORY_DESCRIPTOR, WDF_NO_OBJECT_ATTRIBUTES,
    WDF_OBJECT_ATTRIBUTES, WDF_OBJECT_CONTEXT_TYPE_INFO, WDF_PNPPOWER_EVENT_CALLBACKS,
    WDF_POWER_DEVICE_STATE, WDF_REQUEST_SEND_OPTIONS, WDF_TIMER_CONFIG, WDFCONTEXT, WDFDEVICE,
    WDFIOTARGET, WDFMEMORY, WDFOBJECT, WDFQUEUE, WDFREQUEST, WDFSPINLOCK, WDFTIMER,
    call_unsafe_wdf_function_binding, hid::HidP_GetCaps, ntddk::KeQueryUnbiasedInterruptTime,
};

use crate::{check, child_attributes, hid, hub, nt_success, shared};

/// `HID_BUFFER_CTL_CODE(106)` from hidclass.h (function-like macro, not generated by bindgen).
const IOCTL_HID_GET_COLLECTION_INFORMATION: ULONG = 0x000B_01A8;
/// `HID_CTL_CODE(100)` from hidclass.h (METHOD_NEITHER).
const IOCTL_HID_GET_COLLECTION_DESCRIPTOR: ULONG = 0x000B_0193;

const POOL_TAG: ULONG = u32::from_le_bytes(*b"mkfl");
/// Largest input report we rewrite in place (the A2520 keyboard report is 10 bytes).
const MAX_REPORT: usize = 64;
/// Synchronous IOCTL timeout: 5 s, relative (negative, 100 ns units).
const IOCTL_TIMEOUT: i64 = -5 * 10_000_000;

/// Per-device state (WDF device context).
#[repr(C)]
struct DeviceContext {
    target: WDFIOTARGET,
    /// Fires the engine's tap timers (Fn double-tap) when no report arrives.
    timer: WDFTIMER,
    /// Guards every field below; read completions may run concurrently.
    lock: WDFSPINLOCK,
    /// Collection preparsed data, non-paged and owned by a WDFMEMORY parented to the device.
    /// Null until EvtDeviceSelfManagedIoInit succeeds; reports pass through unchanged until then.
    preparsed: PHIDP_PREPARSED_DATA,
    input_len: usize,
    /// The Lock key arrives as consumer Menu on this model (`Model::lock_reports_menu`).
    lock_reports_menu: bool,
    /// Shared config generation the engine runs with (see `sync_config`).
    config_gen: u32,
    /// Counted in `Shared::keyboards`.
    counted: bool,
    engine: Engine,
}

/// `WDF_DECLARE_CONTEXT_TYPE` equivalent. The wrapper only exists to make the static `Sync`.
#[repr(transparent)]
struct ContextTypeInfo(WDF_OBJECT_CONTEXT_TYPE_INFO);

// SAFETY: the type info is immutable and only read by the framework.
unsafe impl Sync for ContextTypeInfo {}

static DEVICE_CONTEXT_TYPE: ContextTypeInfo = ContextTypeInfo(WDF_OBJECT_CONTEXT_TYPE_INFO {
    Size: size_of::<WDF_OBJECT_CONTEXT_TYPE_INFO>() as ULONG,
    ContextName: c"DeviceContext".as_ptr(),
    ContextSize: size_of::<DeviceContext>(),
    UniqueType: &DEVICE_CONTEXT_TYPE.0,
    EvtDriverGetUniqueContextType: None,
});

/// Monotonic milliseconds for the engine's tap timers (wraps after ~49 days, which it handles).
fn now_ms() -> u32 {
    (unsafe { KeQueryUnbiasedInterruptTime() } / 10_000) as u32
}

/// # Safety
/// `device` must be a WDFDEVICE created with `DEVICE_CONTEXT_TYPE`.
unsafe fn device_context(device: WDFDEVICE) -> *mut DeviceContext {
    unsafe {
        call_unsafe_wdf_function_binding!(
            WdfObjectGetTypedContextWorker,
            device as WDFOBJECT,
            DEVICE_CONTEXT_TYPE.0.UniqueType
        )
    }
    .cast()
}

/// EvtDriverDeviceAdd for a keyboard collection devnode.
///
/// # Safety
/// Called from EvtDriverDeviceAdd with the framework's `init`; PASSIVE_LEVEL.
pub unsafe fn device_add(mut init: PWDFDEVICE_INIT) -> NTSTATUS {
    unsafe { call_unsafe_wdf_function_binding!(WdfFdoInitSetFilter, init) };

    let mut pnp_callbacks = WDF_PNPPOWER_EVENT_CALLBACKS {
        Size: size_of::<WDF_PNPPOWER_EVENT_CALLBACKS>() as ULONG,
        EvtDeviceSelfManagedIoInit: Some(evt_self_managed_io_init),
        EvtDeviceSelfManagedIoCleanup: Some(evt_self_managed_io_cleanup),
        EvtDeviceD0Exit: Some(evt_d0_exit),
        ..Default::default()
    };
    unsafe {
        call_unsafe_wdf_function_binding!(
            WdfDeviceInitSetPnpPowerEventCallbacks,
            init,
            &mut pnp_callbacks
        )
    };

    let mut attributes = WDF_OBJECT_ATTRIBUTES {
        Size: size_of::<WDF_OBJECT_ATTRIBUTES>() as ULONG,
        ExecutionLevel: WdfExecutionLevelInheritFromParent,
        SynchronizationScope: WdfSynchronizationScopeInheritFromParent,
        ContextTypeInfo: &DEVICE_CONTEXT_TYPE.0,
        ..Default::default()
    };
    let mut device: WDFDEVICE = null_mut();
    let status = unsafe {
        call_unsafe_wdf_function_binding!(WdfDeviceCreate, &mut init, &mut attributes, &mut device)
    };
    if !nt_success(status) {
        println!("mkfilter: WdfDeviceCreate failed {status:#010x}");
        return status;
    }

    // The framework zeroes the context; `engine` must be written before anything reads it.
    let ctx = unsafe { device_context(device) };
    unsafe {
        addr_of_mut!((*ctx).engine).write(Engine::new(Config::default()));
        (*ctx).target = call_unsafe_wdf_function_binding!(WdfDeviceGetIoTarget, device);
    }

    let mut lock_attributes = child_attributes(device);
    let status = unsafe {
        call_unsafe_wdf_function_binding!(
            WdfSpinLockCreate,
            &mut lock_attributes,
            addr_of_mut!((*ctx).lock)
        )
    };
    if !nt_success(status) {
        println!("mkfilter: WdfSpinLockCreate failed {status:#010x}");
        return status;
    }

    let mut timer_config = WDF_TIMER_CONFIG {
        Size: size_of::<WDF_TIMER_CONFIG>() as ULONG,
        EvtTimerFunc: Some(evt_timer),
        ..Default::default()
    };
    let mut timer_attributes = child_attributes(device);
    let status = unsafe {
        call_unsafe_wdf_function_binding!(
            WdfTimerCreate,
            &mut timer_config,
            &mut timer_attributes,
            addr_of_mut!((*ctx).timer)
        )
    };
    if !nt_success(status) {
        println!("mkfilter: WdfTimerCreate failed {status:#010x}");
        return status;
    }

    // Default parallel queue with only a read handler: as a filter, the framework forwards every
    // other request type to the lower driver untouched.
    let mut queue_config = WDF_IO_QUEUE_CONFIG {
        Size: size_of::<WDF_IO_QUEUE_CONFIG>() as ULONG,
        DispatchType: WdfIoQueueDispatchParallel,
        PowerManaged: WdfUseDefault,
        DefaultQueue: 1,
        EvtIoRead: Some(evt_io_read),
        ..Default::default()
    };
    queue_config.Settings.Parallel.NumberOfPresentedRequests = ULONG::MAX;
    let status = unsafe {
        call_unsafe_wdf_function_binding!(
            WdfIoQueueCreate,
            device,
            &mut queue_config,
            WDF_NO_OBJECT_ATTRIBUTES,
            null_mut()
        )
    };
    println!("mkfilter: device added {status:#010x}");
    status
}

/// Runs once after the lower stack has started (PASSIVE_LEVEL). Never fails the device: on any
/// error the filter stays in pass-through mode and the keyboard keeps working as before.
extern "C" fn evt_self_managed_io_init(device: WDFDEVICE) -> NTSTATUS {
    match unsafe { load_collection(device) } {
        Ok(pid) => println!(
            "mkfilter: remapping on, PID {pid:04X}, virtual device {}",
            if hub::is_ready() { "ready" } else { "missing" }
        ),
        Err(status) => println!("mkfilter: pass-through, collection setup failed {status:#010x}"),
    }
    STATUS_SUCCESS
}

/// Device going away: drop it from the keyboard count reported to the app.
extern "C" fn evt_self_managed_io_cleanup(device: WDFDEVICE) {
    unsafe {
        let ctx = device_context(device);
        if (*ctx).counted {
            (*ctx).counted = false;
            shared::with(|s| {
                s.keyboards = s.keyboards.saturating_sub(1);
                s.status_changed();
            });
        }
    }
}

/// Leaving D0 (sleep, unplug, disable): release everything the engine holds on the virtual device
/// so no media key or shortcut stays pressed.
extern "C" fn evt_d0_exit(device: WDFDEVICE, _target_state: WDF_POWER_DEVICE_STATE) -> NTSTATUS {
    unsafe {
        let ctx = device_context(device);
        // Wait for a running timer callback; it takes the device lock, which we do not hold yet.
        let _ = call_unsafe_wdf_function_binding!(WdfTimerStop, (*ctx).timer, 1);
        let mut out = Outputs::default();
        call_unsafe_wdf_function_binding!(WdfSpinLockAcquire, (*ctx).lock);
        (*ctx).engine.release_all(&mut out);
        hub::submit(&out);
        call_unsafe_wdf_function_binding!(WdfSpinLockRelease, (*ctx).lock);
    }
    STATUS_SUCCESS
}

/// Engine timer (DISPATCH_LEVEL): fires a deferred Fn double-tap when no report arrives.
extern "C" fn evt_timer(timer: WDFTIMER) {
    unsafe {
        let device = call_unsafe_wdf_function_binding!(WdfTimerGetParentObject, timer) as WDFDEVICE;
        let ctx = device_context(device);
        let mut out = Outputs::default();
        call_unsafe_wdf_function_binding!(WdfSpinLockAcquire, (*ctx).lock);
        // A config the app sent since the last report must be in place before a Fn-lock toggle
        // fires and is published.
        sync_config(ctx);
        let now = now_ms();
        (*ctx).engine.tick(now, &mut out);
        hub::submit(&out);
        publish(ctx, &out);
        schedule_timer(ctx, now);
        call_unsafe_wdf_function_binding!(WdfSpinLockRelease, (*ctx).lock);
    }
}

/// (Re)arms the timer for the engine's next deadline. Caller holds the device lock.
///
/// # Safety
/// `ctx` must be a live device context.
unsafe fn schedule_timer(ctx: *mut DeviceContext, now: u32) {
    if let Some(at) = unsafe { (*ctx).engine.next_deadline() } {
        let delay_ms = (at.wrapping_sub(now) as i32).max(1) as i64;
        unsafe {
            let _ =
                call_unsafe_wdf_function_binding!(WdfTimerStart, (*ctx).timer, -delay_ms * 10_000);
        };
    }
}

/// Fetches the collection's preparsed data, picks the configuration and arms the engine.
///
/// # Safety
/// `device` must be a WDFDEVICE created by `device_add`; PASSIVE_LEVEL.
unsafe fn load_collection(device: WDFDEVICE) -> Result<u16, NTSTATUS> {
    let ctx = unsafe { device_context(device) };
    let target = unsafe { (*ctx).target };

    let mut info: _HID_COLLECTION_INFORMATION = unsafe { zeroed() };
    unsafe {
        ioctl_sync(
            target,
            IOCTL_HID_GET_COLLECTION_INFORMATION,
            (&raw mut info).cast(),
            size_of::<_HID_COLLECTION_INFORMATION>() as ULONG,
        )
    }?;

    let mut memory_attributes = child_attributes(device);
    let mut memory: WDFMEMORY = null_mut();
    let mut buffer: PVOID = null_mut();
    check(unsafe {
        call_unsafe_wdf_function_binding!(
            WdfMemoryCreate,
            &mut memory_attributes,
            NonPagedPoolNx,
            POOL_TAG,
            info.DescriptorSize as usize,
            &mut memory,
            &mut buffer
        )
    })?;
    unsafe {
        ioctl_sync(
            target,
            IOCTL_HID_GET_COLLECTION_DESCRIPTOR,
            buffer,
            info.DescriptorSize,
        )
    }?;
    let preparsed: PHIDP_PREPARSED_DATA = buffer.cast();

    let mut caps: _HIDP_CAPS = unsafe { zeroed() };
    let status = unsafe { HidP_GetCaps(preparsed, &mut caps) };
    if status != hid::HIDP_STATUS_SUCCESS {
        return Err(status);
    }
    let input_len = caps.InputReportByteLength as usize;
    if input_len == 0 || input_len > MAX_REPORT {
        return Err(STATUS_NOT_SUPPORTED);
    }

    let model = model::find(model::APPLE_USB_VID, info.ProductID);
    let (config, config_gen) = shared::with(|s| {
        s.keyboards = s.keyboards.saturating_add(1);
        s.last_pid = info.ProductID;
        s.status_changed();
        (s.config.config, s.config.generation)
    })
    .unwrap_or((None, 0));
    let config = config.unwrap_or_else(|| model.map(Config::default_for).unwrap_or_default());
    unsafe {
        call_unsafe_wdf_function_binding!(WdfSpinLockAcquire, (*ctx).lock);
        (*ctx).engine = Engine::new(config);
        (*ctx).config_gen = config_gen;
        (*ctx).counted = true;
        (*ctx).input_len = input_len;
        (*ctx).lock_reports_menu = model.is_some_and(model::Model::lock_reports_menu);
        (*ctx).preparsed = preparsed;
        call_unsafe_wdf_function_binding!(WdfSpinLockRelease, (*ctx).lock);
    }
    Ok(info.ProductID)
}

/// Sends a buffered-output IOCTL to the lower stack and waits for it. hidclass accepts the
/// collection IOCTLs as both device and internal device control; try the former first.
///
/// # Safety
/// `output` must be valid for `length` bytes; PASSIVE_LEVEL.
unsafe fn ioctl_sync(
    target: WDFIOTARGET,
    code: ULONG,
    output: PVOID,
    length: ULONG,
) -> Result<(), NTSTATUS> {
    let mut descriptor = WDF_MEMORY_DESCRIPTOR {
        Type: WdfMemoryDescriptorTypeBuffer,
        u: _WDF_MEMORY_DESCRIPTOR__bindgen_ty_1 {
            BufferType: _WDF_MEMORY_DESCRIPTOR__bindgen_ty_1__bindgen_ty_1 {
                Buffer: output,
                Length: length,
            },
        },
    };
    let mut options = WDF_REQUEST_SEND_OPTIONS {
        Size: size_of::<WDF_REQUEST_SEND_OPTIONS>() as ULONG,
        Flags: WDF_REQUEST_SEND_OPTION_TIMEOUT as ULONG,
        Timeout: IOCTL_TIMEOUT,
    };
    let mut returned: ULONG_PTR = 0;
    let status = unsafe {
        call_unsafe_wdf_function_binding!(
            WdfIoTargetSendIoctlSynchronously,
            target,
            null_mut(),
            code,
            null_mut(),
            &mut descriptor,
            &mut options,
            &mut returned
        )
    };
    if nt_success(status) {
        return Ok(());
    }
    println!("mkfilter: IOCTL {code:#x} failed {status:#010x}, retrying as internal");
    check(unsafe {
        call_unsafe_wdf_function_binding!(
            WdfIoTargetSendInternalIoctlSynchronously,
            target,
            null_mut(),
            code,
            null_mut(),
            &mut descriptor,
            &mut options,
            &mut returned
        )
    })
}

/// Applies a configuration pushed through the control interface since this device last looked.
/// Caller holds the device lock.
///
/// # Safety
/// `ctx` must be a live device context.
unsafe fn sync_config(ctx: *mut DeviceContext) {
    let seen = unsafe { (*ctx).config_gen };
    let update = shared::with(|s| s.config.update_since(seen));
    if let Some(Some((generation, config))) = update {
        unsafe {
            if let Some(config) = config {
                (*ctx).engine.set_config(config);
            }
            (*ctx).config_gen = generation;
        }
    }
}

/// Publishes engine-side changes (Fn lock toggled by a double tap) to the shared state so the app
/// and the other keyboards see them. Only the top-row mode is written, so a config the app sent
/// meanwhile is kept; this device re-applies the merged config before its next report.
/// Not persisted: the registry can only be written at PASSIVE_LEVEL.
/// Caller holds the device lock.
///
/// # Safety
/// `ctx` must be a live device context.
unsafe fn publish(ctx: *mut DeviceContext, out: &Outputs) {
    if let Some(Notification::FnLockChanged(mode)) = out.notification {
        // Used only while no user config is set, when the engine runs with its model defaults.
        let defaults = unsafe { *(*ctx).engine.config() };
        shared::with(|s| {
            s.config.set_fn_mode(mode, defaults);
            s.status_changed();
        });
    }
}

extern "C" fn evt_io_read(queue: WDFQUEUE, request: WDFREQUEST, _length: usize) {
    unsafe {
        let device = call_unsafe_wdf_function_binding!(WdfIoQueueGetDevice, queue);
        let ctx = device_context(device);
        call_unsafe_wdf_function_binding!(WdfRequestFormatRequestUsingCurrentType, request);
        call_unsafe_wdf_function_binding!(
            WdfRequestSetCompletionRoutine,
            request,
            Some(read_complete),
            ctx as WDFCONTEXT
        );
        if call_unsafe_wdf_function_binding!(WdfRequestSend, request, (*ctx).target, null_mut())
            == 0
        {
            let status = call_unsafe_wdf_function_binding!(WdfRequestGetStatus, request);
            println!("mkfilter: WdfRequestSend failed {status:#010x}");
            call_unsafe_wdf_function_binding!(WdfRequestComplete, request, status);
        }
    }
}

/// Read completion, at IRQL <= DISPATCH_LEVEL.
extern "C" fn read_complete(
    request: WDFREQUEST,
    _target: WDFIOTARGET,
    params: PWDF_REQUEST_COMPLETION_PARAMS,
    context: WDFCONTEXT,
) {
    unsafe {
        let status = (*params).IoStatus.__bindgen_anon_1.Status;
        let information = (*params).IoStatus.Information;
        if nt_success(status) && information > 0 {
            let mut buffer: PVOID = null_mut();
            let mut length = 0usize;
            let st = call_unsafe_wdf_function_binding!(
                WdfRequestRetrieveOutputBuffer,
                request,
                1,
                &mut buffer,
                &mut length
            );
            if st == STATUS_SUCCESS {
                let report = core::slice::from_raw_parts_mut(
                    buffer.cast::<u8>(),
                    length.min(information as usize),
                );
                remap(context.cast(), report);
            }
        }
        call_unsafe_wdf_function_binding!(
            WdfRequestCompleteWithInformation,
            request,
            status,
            information
        );
    }
}

/// Rewrites one input report in place and submits the virtual outputs. Leaves the report untouched
/// if the collection isn't set up yet, the length is unexpected or the parser rejects it.
///
/// # Safety
/// `ctx` must be the context of the device that completed the read; IRQL <= DISPATCH_LEVEL.
unsafe fn remap(ctx: *mut DeviceContext, report: &mut [u8]) {
    let mut original = [0u8; MAX_REPORT];
    let mut out = Outputs::default();
    unsafe {
        let lock = (*ctx).lock;
        call_unsafe_wdf_function_binding!(WdfSpinLockAcquire, lock);
        let preparsed = (*ctx).preparsed;
        if preparsed.is_null() || report.len() != (*ctx).input_len {
            call_unsafe_wdf_function_binding!(WdfSpinLockRelease, lock);
            return;
        }
        original[..report.len()].copy_from_slice(report);
        let Some((state, usages)) = hid::decode(preparsed, report, (*ctx).lock_reports_menu) else {
            call_unsafe_wdf_function_binding!(WdfSpinLockRelease, lock);
            return;
        };
        sync_config(ctx);
        let now = now_ms();
        (*ctx).engine.process(&state, now, &mut out);
        let status = hid::encode(preparsed, report, &out.keyboard);
        if status != hid::HIDP_STATUS_SUCCESS {
            report.copy_from_slice(&original[..report.len()]);
        }
        // Submitted under the device lock so virtual reports keep the order of the input reports.
        hub::submit(&out);
        publish(ctx, &out);
        schedule_timer(ctx, now);
        call_unsafe_wdf_function_binding!(WdfSpinLockRelease, lock);

        // Debug builds only: logging reports exposes keystrokes to anyone capturing kernel
        // debug output. Release builds never log report contents.
        #[cfg(debug_assertions)]
        {
            let raw = &original[..report.len()];
            println!("mkfilter: {raw:02X?} {usages:?} -> {report:02X?} ({status:#010x})");
            if out.any_virtual_change() {
                println!(
                    "mkfilter:   virtual{}: kbd {:?} consumer {:04X?} system {:02X}",
                    if hub::is_ready() {
                        ""
                    } else {
                        " (no hub, dropped)"
                    },
                    out.virt_keyboard,
                    out.consumer,
                    out.system
                );
            }
        }
        #[cfg(not(debug_assertions))]
        let _ = (usages, status);
    }
}
