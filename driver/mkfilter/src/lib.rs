//! mkfilter: KMDF lower filter for the keyboard collection of Apple Magic Keyboards
//! (`HID\VID_05AC&PID_xxxx&MI_01&Col01`).
//!
//! It sits between kbdhid and the hidclass PDO, so every input report kbdhid reads passes through
//! our IRP_MJ_READ completion. Each report is decoded with the collection's preparsed data, run
//! through the mk-core engine and rebuilt in place with keyboard-page usages only. Virtual outputs
//! (media keys, shortcuts) are dropped until the VHF device exists (M5).
//!
//! Debug builds log every report with `DbgPrint` (view with DebugView, "Capture Kernel" + verbose
//! output); release builds never log report contents.

#![no_std]

